export type Text = keyof typeof english;
export function translate(locale: Locale, text: Text): string {
  return locale === 'en' ? english[text] : text;
}
export function localizedPath(locale: Locale, path: string) {
  return locale === 'en' ? `/en${path}` : path;
}
export function formatMoney(kopecks: number, locale: Locale) {
  return new Intl.NumberFormat(locale === 'en' ? 'en-GB' : 'ru-RU', {
    style: 'currency', currency: 'RUB', minimumFractionDigits: 0, maximumFractionDigits: 2,
  }).format(kopecks / 100);
}
